"""Structured machine-log data behind the 'Access-controller export' evidence (deterministically generated).

The numbers are fictional case data. They exist so anomaly detection runs over real arrays instead of hand-written
conclusions: CAM-7's heartbeat is perfectly regular because it is generated by software, not a camera.
"""

from __future__ import annotations

import random

DEVICES = ["CAM-1", "CAM-2", "CAM-3", "CAM-4", "CAM-5", "CAM-6", "CAM-7"]


def heartbeat_intervals(n: int = 720, seed: int = 11) -> dict[str, list[float]]:
    """Seconds between consecutive 'ONLINE' pings, per device."""
    rng = random.Random(seed)
    out: dict[str, list[float]] = {}
    for dev in DEVICES:
        if dev == "CAM-7":
            out[dev] = [60.0] * n  # synthetic keep-alive: zero jitter
        else:
            sigma = rng.uniform(0.18, 0.55)
            out[dev] = [max(58.0, 60.0 + rng.gauss(0, sigma)) for _ in range(n)]
    return out


# (person, door, seconds since midnight in STATION time, direction)
def badge_sessions(seed: int = 5) -> list[dict]:
    """Badge sessions: IN with optional OUT (None = no exit logged)."""
    rng = random.Random(seed)
    sessions = []
    # ordinary staff: short visits with matching exits
    people = ["porter-1", "porter-2", "clerk-1", "guard-2", "cleaner-1", "electrician-1"]
    for _i in range(34):
        who = rng.choice(people)
        door = rng.choice(["SR-DOOR", "SIDING-GATE", "YARD-OFFICE"])
        t_in = rng.randint(6 * 3600, 21 * 3600)
        dwell = int(rng.lognormvariate(5.7, 0.5))
        sessions.append({"person": who, "door": door, "t_in": t_in, "t_out": t_in + dwell})
    # the evening in question
    sessions += [
        {"person": "K.RATHORE", "door": "SR-DOOR", "t_in": 21 * 3600 + 58 * 60, "t_out": None},
        {"person": "K.RATHORE", "door": "SIDING-GATE", "t_in": 22 * 3600 + 41 * 60 + 7, "t_out": 22 * 3600 + 44 * 60 + 20},
        {"person": "K.RATHORE", "door": "SR-DOOR", "t_in": 22 * 3600 + 49 * 60 + 12, "t_out": None},
    ]
    return sessions
